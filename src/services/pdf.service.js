const path = require('path');
const PDFDocument = require('pdfkit');

const LOGO_PATH = path.join(__dirname, '..', '..', 'public', 'images', 'kwust.jpg');

function formatDate(value) {
  if (!value) return 'N/A';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return String(value);
  return date.toLocaleDateString('en-KE', { year: 'numeric', month: 'long', day: 'numeric' });
}

function formatDateTime(value = new Date()) {
  const date = new Date(value);
  return date.toLocaleString('en-KE', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
}

function safeFilename(value) {
  return String(value || 'document').replace(/[^a-z0-9\-_]+/gi, '-').replace(/^-+|-+$/g, '');
}

function drawHeader(doc, title) {
  try {
    doc.image(LOGO_PATH, 50, 45, { width: 54 });
  } catch {
    // Logo is optional; continue with text-only header.
  }

  doc
    .font('Helvetica-Bold')
    .fontSize(12)
    .text('KIRIRI WOMEN’S UNIVERSITY OF SCIENCE AND TECHNOLOGY', 120, 48, { width: 420 })
    .font('Helvetica')
    .fontSize(10)
    .text('This is a document generated by KWUST SmartHealth', 120, 68)
    .moveDown(0.8);

  doc
    .font('Helvetica-Bold')
    .fontSize(13)
    .text(title, 50, 118, { align: 'center' })
    .moveDown(0.4);

  doc
    .font('Helvetica')
    .fontSize(8)
    .fillColor('#555555')
    .text(`Generated: ${formatDateTime()}`, 50, doc.y, { align: 'right' })
    .fillColor('#000000');

  doc.moveDown(0.8);
  doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#cccccc').stroke();
  doc.moveDown(0.8);
}

function labelValue(doc, label, value) {
  doc.font('Helvetica-Bold').fontSize(9).text(`${label}: `, { continued: true });
  doc.font('Helvetica').fontSize(9).text(value || 'N/A');
}

function section(doc, title) {
  doc.moveDown(0.6);
  doc.font('Helvetica-Bold').fontSize(11).fillColor('#1d4ed8').text(title);
  doc.fillColor('#000000').moveDown(0.3);
}

function streamRecordPdf(record, res) {
  const filename = `medical-record-${safeFilename(record.student_id?.admission_number || record.student_id?.full_name)}-${record.id}.pdf`;
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

  const doc = new PDFDocument({ size: 'A4', margin: 50 });
  doc.pipe(res);
  drawHeader(doc, 'MEDICAL RECORD');

  section(doc, 'Patient Details');
  labelValue(doc, 'Full name', record.student_id?.full_name);
  labelValue(doc, 'Admission number', record.student_id?.admission_number);
  labelValue(doc, 'Visit date', formatDate(record.visit_date));
  labelValue(doc, 'Attending clinician', record.clinician_id?.full_name || record.clinician_id?.staff_title);

  section(doc, 'Clinical Notes');
  labelValue(doc, 'Chief complaint', record.chief_complaint);
  labelValue(doc, 'Symptoms', record.symptoms);
  labelValue(doc, 'Diagnosis', record.diagnosis);
  labelValue(doc, 'Notes', record.notes);

  section(doc, 'Prescriptions');
  const prescriptions = record.prescriptions || [];
  if (!prescriptions.length) {
    doc.font('Helvetica').fontSize(9).text('No medicines were prescribed for this visit.');
  } else {
    prescriptions.forEach((item, index) => {
      const medicine = item.medicine_id || {};
      doc
        .font('Helvetica-Bold')
        .fontSize(9)
        .text(`${index + 1}. ${medicine.name || 'Medicine'}`);
      doc
        .font('Helvetica')
        .fontSize(9)
        .text(`Dosage: ${item.dosage || 'N/A'}   Frequency: ${item.frequency || 'N/A'}   Duration: ${item.duration || 'N/A'}   Quantity: ${item.quantity || 'N/A'}`);
      if (item.instructions) doc.fontSize(9).text(`Instructions: ${item.instructions}`);
      doc.moveDown(0.35);
    });
  }

  doc.moveDown(1.5);
  doc.font('Helvetica').fontSize(8).fillColor('#666666')
    .text('This document was generated by KWUST SmartHealth. It is confidential and intended for the named patient only.', 50, doc.y, { width: 495, align: 'center' });

  doc.end();
}

